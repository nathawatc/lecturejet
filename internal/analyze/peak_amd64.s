#include "textflag.h"

// func peakAbsAVX2(samples []float32) float32
TEXT ·peakAbsAVX2(SB), NOSPLIT, $0-28
	MOVQ samples_base+0(FP), SI
	MOVQ samples_len+8(FP), CX

	VXORPS X0, X0, X0
	CMPQ CX, $0
	JE done

	MOVL $0x7fffffff, AX
	VMOVD AX, X7
	VPBROADCASTD X7, Y7

	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3

loop32:
	CMPQ CX, $32
	JL loop8

	VMOVUPS (SI), Y4
	VANDPS Y7, Y4, Y4
	VMAXPS Y4, Y0, Y0

	VMOVUPS 32(SI), Y5
	VANDPS Y7, Y5, Y5
	VMAXPS Y5, Y1, Y1

	VMOVUPS 64(SI), Y6
	VANDPS Y7, Y6, Y6
	VMAXPS Y6, Y2, Y2

	VMOVUPS 96(SI), Y4
	VANDPS Y7, Y4, Y4
	VMAXPS Y4, Y3, Y3

	ADDQ $128, SI
	SUBQ $32, CX
	JMP loop32

loop8:
	VMAXPS Y1, Y0, Y0
	VMAXPS Y3, Y2, Y2
	VMAXPS Y2, Y0, Y0

loop8_inner:
	CMPQ CX, $8
	JL remainder
	VMOVUPS (SI), Y4
	VANDPS Y7, Y4, Y4
	VMAXPS Y4, Y0, Y0
	ADDQ $32, SI
	SUBQ $8, CX
	JMP loop8_inner

remainder:
	VEXTRACTF128 $1, Y0, X1
	VMAXPS X1, X0, X0
	VSHUFPS $0x4E, X0, X0, X1
	VMAXPS X1, X0, X0
	VSHUFPS $0xE5, X0, X0, X1
	VMAXSS X1, X0, X0

loop1:
	CMPQ CX, $0
	JE done
	VMOVSS (SI), X1
	VANDPS X7, X1, X1
	VMAXSS X1, X0, X0
	ADDQ $4, SI
	DECQ CX
	JMP loop1

done:
	VZEROUPPER
	MOVSS X0, ret+24(FP)
	RET
